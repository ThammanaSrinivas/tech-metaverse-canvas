#!/usr/bin/env node
// npm run fonts:subset: cuts each font of the active typography set down to the site's core
// characters (typography.json "core"), so a page downloads about a third less font before its text
// is on brand. Writes, per face:
//   public/fonts/<name>.core.woff2   only the core characters (all axes, features and metrics kept)
// and src/theme/fontSubsets.json: each face's core file and `rest`, the unicode-range of every other
// character the full file has. runtime.ts declares both files as one family, split by unicode-range:
// the browser fetches the full file only for a page that uses a character outside the core.
// Rerun after changing a font file, the active set, or the core range.
import fs from 'node:fs';
import subsetFont from 'subset-font';
import fontverter from 'fontverter';
import { Blob, Face } from 'harfbuzzjs';

const typo = JSON.parse(fs.readFileSync('src/theme/typography.json', 'utf8'));
const set = typo.sets.find((s) => s.name === typo.active.set);
const families = new Set([set.display, set.accent, set.sans, set.mono].filter(Boolean));

/** "U+0020-007E, U+00E9" ↔ code points. */
const parse = (range) =>
  range.split(',').flatMap((part) => {
    const [a, b = a] = part.trim().replace(/^U\+/i, '').split('-');
    const [lo, hi] = [parseInt(a, 16), parseInt(b, 16)];
    return Array.from({ length: hi - lo + 1 }, (_, i) => lo + i);
  });
const format = (points) => {
  const runs = [];
  for (const c of [...points].sort((x, y) => x - y)) {
    const last = runs.at(-1);
    if (last && c === last[1] + 1) last[1] = c;
    else runs.push([c, c]);
  }
  const hex = (c) => c.toString(16).toUpperCase().padStart(4, '0');
  return runs.map(([lo, hi]) => (lo === hi ? `U+${hex(lo)}` : `U+${hex(lo)}-${hex(hi)}`)).join(', ');
};

const core = new Set(parse(typo.core.range));
const out = { _about: 'Generated by scripts/subset-fonts.mjs (npm run fonts:subset); do not edit by hand.' };
for (const face of typo.faces.filter((f) => families.has(f.family))) {
  if (!face.file.endsWith('.woff2')) throw new Error(`${face.file}: only woff2 faces are cut`);
  const font = fs.readFileSync(`public${face.file}`);
  const has = new Face(new Blob(await fontverter.convert(font, 'truetype'))).collectUnicodes();
  const keep = [...has].filter((c) => core.has(c));
  const file = face.file.replace(/\.woff2$/, '.core.woff2');
  const cut = await subsetFont(font, String.fromCodePoint(...keep), { targetFormat: 'woff2' });
  fs.writeFileSync(`public${file}`, cut);
  out[face.file] = { core: file, rest: format([...has].filter((c) => !core.has(c))) };
  console.log(`${file}: ${keep.length} characters, ${(font.length / 1024).toFixed(0)} → ${(cut.length / 1024).toFixed(0)} KB`);
}
fs.writeFileSync('src/theme/fontSubsets.json', `${JSON.stringify(out, null, 2)}\n`);
